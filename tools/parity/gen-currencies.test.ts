// Emits internal/money/currencies_gen.go from Node's Intl so Go matches `money()` exactly.
import { test } from "vitest";
import { writeFileSync } from "node:fs";

test("currencies", () => {
  const rows: string[] = [];
  for (const code of Intl.supportedValuesOf("currency")) {
    const f = new Intl.NumberFormat("en-US", { style: "currency", currency: code, currencyDisplay: "narrowSymbol", maximumFractionDigits: 0 });
    const pos = f.format(1234);
    const prefix = pos.replace("1,234", "");
    if (pos !== prefix + "1,234" || pos.includes("1,234" + "x")) throw new Error(`unexpected positive format for ${code}: ${pos}`);
    if (f.format(-1234) !== "-" + prefix + "1,234") throw new Error(`unexpected negative format for ${code}: ${f.format(-1234)}`);
    if (f.format(0) !== prefix + "0") throw new Error(`unexpected zero format for ${code}`);
    rows.push(`\t${JSON.stringify(code)}: ${JSON.stringify(prefix)},`);
  }
  writeFileSync(process.env.OUT!, `// Code generated by tools/parity/gen-currencies.test.ts; DO NOT EDIT.\n\npackage money\n\n// prefixes maps an ISO 4217 code to the en-US narrowSymbol prefix (digits follow it).\nvar prefixes = map[string]string{\n${rows.join("\n")}\n}\n`);
});
